const int N = 1e6 + 10, mod = 998244353, INF = 1e18;

int read() {
	int x = 0, f = 1;
	char ch = getchar();
	while(ch < '0' || ch > '9') {
		if(ch == '-') f = -1;
		ch = getchar();
	}
	while(ch >= '0' && ch <= '9') {
		x = x * 10 + ch - '0';
		ch = getchar();
	}
	return x * f;
}

void solve() {
	int n = read(), m = read();
	for(int i = 1; i <= m; i++) {
		std::string s = "";
		std::cin >> s;
		int ans = 1, now = n - 1;
		for(int j = 0; j < s.size(); j++) {
			if(s[j] == 'n') ans += (1ll << now);
			now--;
		}
		std::cout << ans << '\n';
	}
}
signed main() {
	int T = 1;
	while(T--) {
		solve();
//		init();
	}
	return 0;
}
